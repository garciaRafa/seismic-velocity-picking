"""
src/optimizers/base.py
----------------------
Abstract base class for all metaheuristic optimizers.
All algorithm implementations must inherit from this class
to ensure a uniform interface for comparison.
"""

import time
import numpy as np
from abc import ABC, abstractmethod


class BaseOptimizer(ABC):
    """
    Base class for velocity picking metaheuristics.

    Every optimizer receives a CDP gather and searches for the
    set of (time, velocity) pairs that maximizes semblance.

    Parameters
    ----------
    traces     : np.ndarray, shape (n_traces, n_samples)
    offsets    : np.ndarray, shape (n_traces,) in meters
    dt_ms      : float — sampling interval in ms
    vel_min    : float — minimum velocity in m/s
    vel_max    : float — maximum velocity in m/s
    n_picks    : int   — number of velocity picks to find
    max_iter   : int   — maximum number of iterations
    seed       : int   — random seed for reproducibility
    max_evals  : int or None — budget of objective evaluations (one
                 evaluation = one full solution). None means no budget.
    min_sep_ms : float — minimum time separation between consecutive
                 picks, in ms. 0 (default) only requires distinct times.
    t_min_ms   : float — earliest time allowed for a pick, in ms
                 (default 0). Use it to exclude trace segments without
                 reflections, such as the water layer.
    t_max_ms   : float or None — latest time allowed for a pick, in ms
                 (default: end of the record). Use it to exclude the end
                 of the record, where far-offset traces leave the record
                 and semblance is limited by the fraction of live traces.

    objective  : 'mean' (default) or 'threshold'.
                 'mean'      — mean semblance of exactly n_picks picks
                               (formulations v1/v2).
                 'threshold' — sum of (semblance - tau) over a FREE number
                               of picks K, k_min <= K <= k_max
                               (formulation v3). n_picks is ignored.
    tau        : float — threshold of the 'threshold' objective (required
                 there), e.g. from src.seismic.semblance.robust_threshold.
    k_min      : int — minimum number of picks with 'threshold' (default 1)
    k_max      : int or None — maximum number of picks with 'threshold'.
                 None (default) = as many as fit in the time window with
                 min_sep; larger values are clipped to that limit.
    p_insert, p_remove : float — with 'threshold', probability that a
                 neighbor is generated by inserting / removing one pick
                 (see _structural_move). Ignored with 'mean'.
    record_trajectory : bool — store the search trajectory for
                 visualization (off by default). Recording only reads the
                 search state: it draws no random number and does not change
                 the result. Fills self.trajectory (one record per iteration
                 and per (re)start: current solution, its score, the best
                 score, n_evals and algorithm-specific fields) and
                 self.proposals (every new (time, velocity) pick evaluated,
                 i.e. picks of an evaluated solution that are not in the
                 current one).
    record_every : int — keep one trajectory record every `record_every`
                 iterations (starts and restarts are always kept).
    stretch_mute, energy_floor, min_fold : robust-semblance options
                 (src/seismic/semblance.py): NMO stretch mute, energy
                 floor of the denominator and minimum number of live
                 traces. Off by default (plain semblance). The objective,
                 and the panel used to compute tau, must use the same
                 options.

    Formulation
    -----------
    With the defaults (min_sep_ms=0, t_min_ms=0, t_max_ms=None) the
    constraints and the random draws are exactly those of formulation v1,
    so earlier results are reproduced. Setting the three parameters gives
    formulation v2. objective='threshold' gives formulation v3: with the
    'mean' objective (default) no extra random number is ever drawn, so
    v1/v2 runs are reproduced bit-for-bit.

    Randomness
    ----------
    Every optimizer draws random numbers ONLY from its own generator,
    self.rng (numpy Generator). The global np.random state is never used,
    so other code (notebook cells, data generation, other optimizers)
    cannot change the sequence of draws, and the same seed always
    reproduces the same run.
    """

    def __init__(self, traces, offsets, dt_ms,
                 vel_min=1500.0, vel_max=5000.0,
                 n_picks=10, max_iter=200, seed=42, max_evals=None,
                 min_sep_ms=0.0, t_min_ms=0.0, t_max_ms=None,
                 objective='mean', tau=None, k_min=1, k_max=None,
                 p_insert=0.1, p_remove=0.1,
                 stretch_mute=None, energy_floor=0.0, min_fold=1,
                 record_trajectory=False, record_every=1):

        self.traces   = traces
        self.offsets  = offsets
        self.dt_ms    = dt_ms
        self.vel_min  = vel_min
        self.vel_max  = vel_max
        self.n_picks  = n_picks
        self.max_iter  = max_iter
        self.seed      = seed
        self.max_evals = max_evals

        self.n_traces, self.n_samples = traces.shape

        # Time constraints, converted from ms to sample indices
        self.min_sep_ms = float(min_sep_ms)
        self.t_min_ms   = float(t_min_ms)
        self.t_max_ms   = t_max_ms
        self.min_sep = max(1, int(np.ceil(self.min_sep_ms / dt_ms - 1e-9)))
        self.t_min   = max(0, int(np.ceil(self.t_min_ms / dt_ms - 1e-9)))
        self.t_max   = (self.n_samples - 1 if t_max_ms is None else
                        min(self.n_samples - 1,
                            int(np.floor(t_max_ms / dt_ms + 1e-9))))

        # Objective and number of picks
        if objective not in ('mean', 'threshold'):
            raise ValueError("objective must be 'mean' or 'threshold'.")
        self.objective  = objective
        self.variable_k = objective == 'threshold'

        if self.variable_k:
            if tau is None:
                raise ValueError("objective='threshold' needs tau.")
            if not (0.0 <= p_insert and 0.0 <= p_remove
                    and p_insert + p_remove <= 1.0):
                raise ValueError("p_insert and p_remove must be >= 0 and "
                                 "add up to at most 1.")
            fit = (self.t_max - self.t_min) // self.min_sep + 1
            self.tau      = float(tau)
            self.k_min    = int(k_min)
            self.k_max    = fit if k_max is None else min(int(k_max), fit)
            self.p_insert = float(p_insert)
            self.p_remove = float(p_remove)
            if not 1 <= self.k_min <= self.k_max:
                raise ValueError(
                    f"k_min={k_min} picks separated by {self.min_sep_ms} ms "
                    f"do not fit in the time window (at most {fit}).")
        else:
            self.tau      = None
            self.k_min    = self.k_max = self.n_picks
            self.p_insert = self.p_remove = 0.0

        if (self.k_min - 1) * self.min_sep > self.t_max - self.t_min:
            raise ValueError(
                f"{self.k_min} picks separated by {self.min_sep_ms} ms "
                f"do not fit between {self.t_min_ms} and {t_max_ms} ms."
            )

        # Robust-semblance options (off by default), passed to the objective
        if stretch_mute is not None and stretch_mute <= 0:
            raise ValueError("stretch_mute must be positive (or None).")
        if energy_floor < 0 or int(min_fold) < 1:
            raise ValueError("energy_floor must be >= 0 and min_fold >= 1.")
        self.stretch_mute = None if stretch_mute is None else float(stretch_mute)
        self.energy_floor = float(energy_floor)
        self.min_fold     = int(min_fold)
        from src.seismic.semblance import gather_energy
        self._semblance_opts = dict(
            stretch_mute=self.stretch_mute, energy_floor=self.energy_floor,
            min_fold=self.min_fold,
            e_ref=gather_energy(traces) if self.energy_floor > 0 else None)

        # Trajectory recording for visualization (off by default)
        self.record_trajectory = bool(record_trajectory)
        self.record_every      = max(1, int(record_every))

        # Own random generator (see "Randomness" above)
        self.rng = np.random.default_rng(seed)

        # Results — filled after run()
        self._reset_run_state()

    def _reset_run_state(self):
        """Clear results and counters before a new run."""
        self.history       = []   # best fitness per iteration
        self.eval_history  = []   # (n_evals, best_score) at each improvement
        self.best_picks    = None # list of (time_sample, velocity)
        self.best_score    = -np.inf
        self.exec_time_s   = None
        self.n_evals       = 0    # objective evaluations performed
        self.trajectory    = []   # search trajectory (record_trajectory=True)
        self._proposals    = []   # new picks evaluated (record_trajectory=True)
        self._n_iter_total = 0    # iterations over all (re)starts

    # ------------------------------------------------------------------ #
    # Abstract methods — must be implemented by each algorithm            #
    # ------------------------------------------------------------------ #

    @abstractmethod
    def _initialize(self):
        """Initialize the search (population, current solution, etc.)."""
        pass

    @abstractmethod
    def _iterate(self):
        """Execute one iteration of the algorithm."""
        pass

    # ------------------------------------------------------------------ #
    # Shared utilities                                                     #
    # ------------------------------------------------------------------ #

    def _evaluate(self, picks):
        """
        Evaluate a candidate solution using semblance as objective.

        Parameters
        ----------
        picks : list of (time_sample, velocity) tuples

        Returns
        -------
        score : float — mean semblance in [0, 1] ('mean' objective), or
                sum of (semblance - tau) ('threshold' objective)
        """
        from src.seismic.semblance import (picking_objective,
                                           picking_objective_threshold)
        self.n_evals += 1
        if self.record_trajectory:
            current = set(getattr(self, '_current_picks', None) or ())
            self._proposals.extend((p[0], p[1], self.n_evals)
                                   for p in picks if p not in current)
        if self.variable_k:
            return picking_objective_threshold(
                self.traces, self.offsets, picks, self.dt_ms, self.tau,
                **self._semblance_opts
            )
        return picking_objective(
            self.traces, self.offsets, picks, self.dt_ms, **self._semblance_opts
        )

    @property
    def budget_exhausted(self):
        """True when the evaluation budget (max_evals) has been used up."""
        return self.max_evals is not None and self.n_evals >= self.max_evals

    def _generate_neighbor(self, picks, step_time, step_vel):
        """
        Perturb one randomly chosen pick: a small random change in time
        and/or velocity. The neighbor is kept sorted by time, so list
        order always matches temporal order.

        Shared by every local-search algorithm (Hill Climbing, Tabu
        Search, ...) so they all explore literally the same
        neighborhood structure — any difference in their results comes
        from the search STRATEGY, not from the move set.

        Parameters
        ----------
        picks     : list of (time_sample, velocity) — current solution
        step_time : int   — max perturbation in time samples
        step_vel  : float — max perturbation in velocity (m/s)

        Returns
        -------
        neighbor : list of (time_sample, velocity) — the perturbed solution
        idx      : int — index of the perturbed pick in the INPUT list
                   (before the re-sort)
        t_old    : int — the pick's time sample before the perturbation
        t_new    : int — the pick's time sample after the perturbation
        """
        neighbor = list(picks)
        idx      = int(self.rng.integers(0, len(picks)))

        t_old, v_old = neighbor[idx]

        dt    = int(self.rng.integers(-step_time, step_time + 1))
        t_new = int(np.clip(t_old + dt, self.t_min, self.t_max))

        dv    = float(self.rng.uniform(-step_vel, step_vel))
        v_new = float(np.clip(v_old + dv, self.vel_min, self.vel_max))

        neighbor[idx] = (t_new, v_new)
        neighbor.sort(key=lambda p: p[0])
        return neighbor, idx, t_old, t_new

    # ------------------------------------------------------------------ #
    # Structural moves — formulation v3 (variable number of picks)         #
    # ------------------------------------------------------------------ #

    def _insert_neighbor(self, picks):
        """
        Add one pick, valid by construction: its time is drawn uniformly
        among all times that keep min_sep from the existing picks (inside
        the time window), and its velocity uniformly between the
        velocities of its two neighbors (monotonicity). The input must be
        a valid, time-sorted solution.

        Returns (neighbor, t_new), or None if no pick can be added
        (k_max reached, or no gap is wide enough).
        """
        if len(picks) >= self.k_max:
            return None

        gaps = []                                 # (position, t_lo, t_hi)
        for j in range(len(picks) + 1):
            t_lo = self.t_min if j == 0 else picks[j - 1][0] + self.min_sep
            t_hi = self.t_max if j == len(picks) else picks[j][0] - self.min_sep
            if t_lo <= t_hi:
                gaps.append((j, t_lo, t_hi))
        if not gaps:
            return None

        # Uniform over every feasible time: pick a gap with probability
        # proportional to its number of feasible samples
        sizes = np.array([t_hi - t_lo + 1 for _, t_lo, t_hi in gaps], float)
        g     = int(self.rng.choice(len(gaps), p=sizes / sizes.sum()))
        j, t_lo, t_hi = gaps[g]
        t_new = int(self.rng.integers(t_lo, t_hi + 1))

        v_lo  = self.vel_min if j == 0 else picks[j - 1][1]
        v_hi  = self.vel_max if j == len(picks) else picks[j][1]
        v_new = float(self.rng.uniform(v_lo, v_hi))

        neighbor = list(picks)
        neighbor.insert(j, (t_new, v_new))
        return neighbor, t_new

    def _remove_neighbor(self, picks):
        """
        Remove one pick chosen uniformly. Removing a pick never breaks
        min_sep or monotonicity, so the result is valid.

        Returns (neighbor, t_old), or None if k_min is reached.
        """
        if len(picks) <= self.k_min:
            return None
        idx = int(self.rng.integers(0, len(picks)))
        neighbor = list(picks)
        t_old, _ = neighbor.pop(idx)
        return neighbor, t_old

    def _structural_move(self, picks):
        """
        With the 'threshold' objective, decide whether the next neighbor
        changes the NUMBER of picks:

            with probability p_insert -> insert one pick
            with probability p_remove -> remove one pick
            otherwise                 -> None (the caller uses its usual
                                         move: shift, jump, ...)

        An insertion or removal that is impossible (k_max / k_min reached,
        no room) also returns None. With the 'mean' objective it returns
        None without drawing any random number, so v1/v2 runs are
        reproduced exactly.

        Returns
        -------
        None, or (neighbor, kind, t_old, t_new) with kind 'insert'
        (t_old = None) or 'remove' (t_new = None).
        """
        if not self.variable_k:
            return None
        r = self.rng.random()
        if r < self.p_insert:
            move = self._insert_neighbor(picks)
            return None if move is None else (move[0], 'insert', None, move[1])
        if r < self.p_insert + self.p_remove:
            move = self._remove_neighbor(picks)
            return None if move is None else (move[0], 'remove', move[1], None)
        return None

    # ------------------------------------------------------------------ #
    # Trajectory recording (visualization only)                            #
    # ------------------------------------------------------------------ #

    def _record_extra(self):
        """Algorithm-specific fields of a trajectory record (override)."""
        return {}

    def _record(self, event, iteration_done=True):
        """
        Store the current state of the search when recording is on.

        event          : 'start', 'restart' or 'iter'
        iteration_done : count this call as one iteration (False for
                         starts and restarts)
        """
        if not self.record_trajectory:
            return
        if iteration_done:
            self._n_iter_total += 1
            if event == 'iter' and self._n_iter_total % self.record_every:
                return
        picks = getattr(self, '_current_picks', None) or self.best_picks or []
        rec = {
            'iteration':     self._n_iter_total,
            'n_evals':       self.n_evals,
            'event':         event,
            'current':       [(int(t), float(v)) for t, v in picks],
            'current_score': float(getattr(self, '_current_score', self.best_score)),
            'best_score':    float(self.best_score),
        }
        rec.update(self._record_extra())
        self.trajectory.append(rec)

    @property
    def proposals(self):
        """
        New picks evaluated during the run, as an array (n, 3) of
        (time sample, velocity, n_evals at that moment). Empty unless
        record_trajectory=True.
        """
        return np.array(self._proposals, dtype=float).reshape(-1, 3)

    def _update_best(self, picks, score):
        """
        Keep the global best solution and record when it improved,
        measured in number of evaluations (for fair comparisons).
        """
        if score > self.best_score:
            self.best_score = score
            self.best_picks = list(picks)
            self.eval_history.append((self.n_evals, score))

    def _is_valid(self, picks):
        """
        Check physical plausibility constraints:
        - velocities within [vel_min, vel_max]
        - times within [t_min, t_max] (sample indices)
        - consecutive times separated by at least min_sep samples
          (min_sep = 1 means only distinct times)
        - velocities increase monotonically with time
        - with the 'threshold' objective: k_min <= number of picks <= k_max
        """
        if self.variable_k and not self.k_min <= len(picks) <= self.k_max:
            return False

        # Sort by time so the check does not depend on list order
        ordered = sorted(picks, key=lambda p: p[0])
        times = [p[0] for p in ordered]
        vels  = [p[1] for p in ordered]

        # Velocity bounds
        if any(v < self.vel_min or v > self.vel_max for v in vels):
            return False

        # Time bounds (allowed time window)
        if any(t < self.t_min or t > self.t_max for t in times):
            return False

        # Minimum separation between consecutive picks (also rejects
        # repeated times, which are always redundant)
        for i in range(1, len(times)):
            if times[i] - times[i - 1] < self.min_sep:
                return False

        # Monotonic velocity increase with time
        for i in range(1, len(vels)):
            if vels[i] < vels[i - 1]:
                return False

        return True

    def _random_picks(self):
        """
        Generate a random valid set of picks.

        Times are drawn uniformly among all sets that respect the time
        window and the minimum separation: K distinct values are drawn
        from a reduced range and then spread apart by (min_sep - 1)
        samples each. With min_sep = 1 and the full window this is
        exactly the formulation v1 draw.

        With the 'threshold' objective the number of picks K is first
        drawn uniformly in [k_min, k_max]; with 'mean', K = n_picks and no
        extra random number is drawn.
        """
        k = (int(self.rng.integers(self.k_min, self.k_max + 1))
             if self.variable_k else self.n_picks)
        gap    = self.min_sep - 1
        n_free = (self.t_max - self.t_min) - (k - 1) * gap + 1
        base   = sorted(int(t) for t in self.rng.choice(
            n_free, k, replace=False
        ))
        times = [self.t_min + b + i * gap for i, b in enumerate(base)]
        vels = sorted(float(v) for v in self.rng.uniform(
            self.vel_min, self.vel_max, k
        ))
        return list(zip(times, vels))

    # ------------------------------------------------------------------ #
    # Main execution                                                       #
    # ------------------------------------------------------------------ #

    def run(self):
        """
        Execute the optimization and return self.

        Usage:
            optimizer = MyOptimizer(traces, offsets, dt_ms)
            optimizer.run()
            times, vels = optimizer.get_result()
        """
        self._reset_run_state()
        self.rng = np.random.default_rng(self.seed)   # same seed, same run
        self._initialize()

        t_start = time.perf_counter()

        for it in range(self.max_iter):
            if self.budget_exhausted:
                break
            self._iterate()

            if self.best_score not in self.history or \
               (self.history and self.best_score > self.history[-1]):
                self.history.append(self.best_score)
            else:
                self.history.append(
                    self.history[-1] if self.history else self.best_score
                )

        self.exec_time_s = time.perf_counter() - t_start
        return self

    def get_result(self):
        """
        Return the best picks found.

        Returns
        -------
        times      : np.ndarray of time samples
        velocities : np.ndarray of velocities in m/s
        """
        if self.best_picks is None:
            raise RuntimeError("Run the optimizer first with .run()")

        times = np.array([p[0] for p in self.best_picks])
        vels  = np.array([p[1] for p in self.best_picks])

        order = np.argsort(times)
        return times[order], vels[order]

    def get_metrics(self, true_velocities=None):
        """
        Return performance metrics.

        Parameters
        ----------
        true_velocities : np.ndarray or None
            If provided, computes RMSE and MAE against ground truth.

        Returns
        -------
        metrics : dict
        """
        metrics = {
            'algorithm':   self.__class__.__name__,
            'best_score':  self.best_score,
            'exec_time_s': self.exec_time_s,
            'n_iter':      len(self.history),
            'n_evals':     self.n_evals,
            'seed':        self.seed,
        }

        if true_velocities is not None:
            _, vels = self.get_result()
            n = min(len(vels), len(true_velocities))
            rmse = np.sqrt(np.mean((vels[:n] - true_velocities[:n]) ** 2))
            mae  = np.mean(np.abs(vels[:n] - true_velocities[:n]))
            metrics['rmse'] = float(rmse)
            metrics['mae']  = float(mae)

        return metrics